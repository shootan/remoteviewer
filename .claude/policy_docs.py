import io

def edit(path, pairs, encoding='utf-8'):
    d = io.open(path, encoding=encoding).read()
    for i, (old, new) in enumerate(pairs):
        assert d.count(old) == 1, '%s pair %d: %s' % (path, i, old[:60])
        d = d.replace(old, new, 1)
    io.open(path, 'w', encoding=encoding, newline='').write(d)
    print('ok', path)


