import io

p = 'docs/업데이트_기능_설계.md'
d = io.open(p, encoding='utf-8').read()

old = '''- 모르는 `directory=` 값은 **무시한다.** 새 제품이 쓴 상태가 옛 업데이터를 우연히 만족시키면 안 된다.'''
new = '''- 모르는 `directory=` 값은 **무시한다.** 새 제품이 쓴 상태가 옛 업데이터를 우연히 만족시키면 안 된다.
- **보고할 주체가 없으면 기다리지 않는다.** 이 줄을 쓰는 것은 호스트뿐이다. 호스트가 업데이트 전에
  돌고 있지 않았다면 재실행 계획에 없고, 그러면 **기다릴 대상 자체가 없다** — 그래도 시한만큼 기다린
  다음 실패로 판정하면, **파일이 전부 올바른 업데이트를 "업데이트 전에 어떤 프로세스가 안 돌고
  있었다" 는 이유로 롤백**하게 된다. 그건 지름길이 아니라 질문을 바로 세우는 것이다: 이 검사가 묻는
  것은 "제품이 살아 있는가" 이지 "없던 것이 생겼는가" 가 아니다. 클라이언트만 돌던 기계의 업데이트가
  이 경우이고(3.11.0), 회귀는 `updater_scenarios_test` 시나리오 9 다.
- **아무것도 재실행되지 않았는데 "건강하다" 고 답하지도 않는다.** 위와 종이 한 장 차이로 보이지만
  반대다 — 재실행 자체가 없었다면 아무도 아무것도 묻지 않은 것이고, 거기에 "예" 라고 답하는 것은
  **묻지 않은 질문에 답하는 것**이다.'''
assert old in d, '3.12 tail'
d = d.replace(old, new, 1)
io.open(p, 'w', encoding='utf-8', newline='').write(d)
print('3.12 now says what 3.11.0 points at')
